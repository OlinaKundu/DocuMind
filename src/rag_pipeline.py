"""RAG pipeline orchestration module for DocuMind.

Phase 5.3: Integrates vector retrieval, context formatting, prompt construction,
and Groq LLM answer generation into a unified, modular, end-to-end question-answering pipeline.
"""

from dataclasses import dataclass
from typing import Any, List, Optional
from src.retriever import SearchResult, VectorStore, retrieve
from src.prompt_builder import build_rag_messages
from src.llm import generate_chat_response, get_model_name


@dataclass(frozen=True)
class RAGResponse:
    """Immutable data container representing the full RAG pipeline response.

    Attributes:
        answer: The text generated by the LLM grounded on the retrieved context.
        sources: The list of SearchResult records retrieved from the vector store.
        model: The identifier of the LLM model used for answer generation.
        question: The original user question.
    """

    answer: str
    sources: List[SearchResult]
    model: str
    question: str

    @property
    def source_count(self) -> int:
        """Returns the number of retrieved source chunks."""
        return len(self.sources)

    @property
    def has_sources(self) -> bool:
        """Returns True if one or more source chunks were retrieved."""
        return len(self.sources) > 0


def answer_question(
    question: str,
    vector_store: VectorStore,
    top_k: int = 5,
    model: Optional[str] = None,
    llm_client: Optional[Any] = None,
    embedding_model: Optional[Any] = None,
    system_prompt: Optional[str] = None,
    temperature: float = 0.0,
    max_tokens: Optional[int] = None,
) -> RAGResponse:
    """Executes the end-to-end RAG pipeline for a user question.

    Sequence:
    1. Validates input parameters.
    2. Retrieves top-k most semantically similar chunks from the FAISS vector store.
    3. Builds evidence context and structured system/user prompt messages.
    4. Sends formatted messages to the Groq LLM client.
    5. Returns a structured RAGResponse bundling the generated answer and original sources.

    Args:
        question: User query string.
        vector_store: VectorStore instance containing indexed document chunks.
        top_k: Maximum number of chunks to retrieve (default: 5).
        model: Optional model identifier override (e.g. 'openai/gpt-oss-120b').
        llm_client: Optional Groq client or mock for testing. If None, default client is created.
        embedding_model: Optional SentenceTransformer model or mock for query embedding.
        system_prompt: Optional system prompt override with custom grounding rules.
        temperature: Sampling temperature for LLM generation (default: 0.0).
        max_tokens: Optional maximum tokens for LLM completion.

    Returns:
        RAGResponse: Structured response containing the answer, retrieved sources,
        active model name, and original question.

    Raises:
        TypeError: If question is not a string, or vector_store is not a VectorStore instance.
        ValueError: If question is empty or contains only whitespace, or top_k is invalid.
        RetrievalError: If vector search fails.
        LLMError: If Groq API call fails (missing key, auth error, rate limit, timeout, empty response).
    """
    # 1. Validate question
    if not isinstance(question, str):
        raise TypeError(f"question must be a string, got {type(question).__name__}.")

    cleaned_question = question.strip()
    if not cleaned_question:
        raise ValueError("question cannot be empty or contain only whitespace.")

    # 2. Validate vector store
    if not isinstance(vector_store, VectorStore):
        raise TypeError(
            f"Expected 'vector_store' to be a VectorStore instance, got {type(vector_store).__name__}."
        )

    # 3. Retrieve top-k relevant chunks (validates top_k internally)
    sources = retrieve(
        query=cleaned_question,
        vector_store=vector_store,
        top_k=top_k,
        model=embedding_model,
    )

    # 4. Construct grounded chat messages (system rules + user evidence block)
    messages = build_rag_messages(
        question=cleaned_question,
        results=sources,
        system_prompt=system_prompt,
    )

    # 5. Resolve active model and generate chat completion
    active_model = get_model_name(model)
    answer = generate_chat_response(
        messages=messages,
        model=active_model,
        client=llm_client,
        temperature=temperature,
        max_tokens=max_tokens,
    )

    # 6. Bundle into immutable response object
    return RAGResponse(
        answer=answer,
        sources=list(sources),
        model=active_model,
        question=cleaned_question,
    )

